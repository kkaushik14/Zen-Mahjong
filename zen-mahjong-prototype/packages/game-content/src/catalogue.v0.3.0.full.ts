function createDesign(seed: CatalogueSeed): TileDesign {
  const [
    designId,
    displayName,
    releaseRole,
    familyId,
    similarityGroup,
    colorIndependentMarker,
    eligibleCategories,
    status,
    artworkId,
  ] = seed;
  const componentId = designId === 'garden-gate' ? 'gate' : designId;
  const assetReference = artworkId
    ? `artwork:v3:${artworkId}`
    : status === 'approved'
      ? `component:${componentId}`
      : `pending:v3:${designId}`;
  return {
    accessibilityLabel: `${displayName} tile`,
    colorIndependentMarker,
    compactMotifAsset: assetReference,
    contentVersion: '0.3.0',
    designId,
    displayName,
    eligibleCategories,
    familyId,
    introducedAtLevel: releaseRole === 'special' ? 7 : 1,
    kind: releaseRole === 'special' ? 'special' : 'regular',
    ...(designId === 'garden-gate' ? { legacyDesignIds: ['gate'] } : {}),
    matchIdentity: designId,
    motifAsset: assetReference,
    releaseRole,
    similarityGroup,
    status,
    visualTags: colorIndependentMarker.split(/[, ]+/).filter(Boolean),
  };
}

export const catalogueData: TileCatalogueV1 = {
  contentVersion: '0.3.0',
  designs: seeds.map(createDesign),
  schemaVersion: 1,
};
